static std::vector<ConstLine> Build(const RawPoly* polys, size_t count,
                                    const double* pts) {
    std::vector<ConstLine> out;
    out.reserve(count);
    for (size_t i = 0; i < count; ++i) {
        ConstLine l;
        l.con = polys[i].con;
        l.nameCn = Utf8ToWide(polys[i].nameCn);
        l.pts.reserve(polys[i].n);
        for (int j = 0; j < polys[i].n; ++j) {
            const double* p = pts + polys[i].off + j * 2;
            l.pts.push_back({ p[0], p[1] });
        }
        if (!l.pts.empty()) out.push_back(std::move(l));
    }
    return out;
}

const std::vector<ConstLine>& BuiltinLines() {
    static const std::vector<ConstLine> v = Build(kPolyLines,
        sizeof(kPolyLines) / sizeof(kPolyLines[0]), kPtsLines);
    return v;
}

const std::vector<ConstLine>& BuiltinBorders() {
    static const std::vector<ConstLine> v = Build(kPolyBorders,
        sizeof(kPolyBorders) / sizeof(kPolyBorders[0]), kPtsBorders);
    return v;
}

